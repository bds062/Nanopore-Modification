#!/usr/bin/env bash
set -euo pipefail

# Run a trained DeepMod checkpoint on one unlabeled event-clustering dataset.
# Required: POD5, EVENT_DIR, OUT_DIR. Everything else has conservative defaults.

REPO_ROOT=${REPO_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}
WORK_ROOT=${WORK_ROOT:-/fs/nexus-scratch/bds062}
PYTHON=${PYTHON:-$WORK_ROOT/envs/rockfish/bin/python}
export PYTHONPATH="$REPO_ROOT:${PYTHONPATH:-}"

DATASET=${DATASET:-deepmod_test}
EVENT_DIR=${EVENT_DIR:?Set EVENT_DIR to the event_clustering output directory}
POD5=${POD5:?Set POD5 to the source POD5 file or directory}
OUT_DIR=${OUT_DIR:?Set OUT_DIR for DeepMod outputs}
MODEL=${MODEL:-$WORK_ROOT/results/deep_modification/results6/best_model.pt}

BAM=${BAM:-}
PEAKS=${PEAKS:-$EVENT_DIR/peaks_refined.tsv}
LEVEL_TABLE=${LEVEL_TABLE:-}
REFERENCE=${REFERENCE:-}
GT_BED=${GT_BED:-}

DEVICE=${DEVICE:-auto}
BATCH_SIZE=${BATCH_SIZE:-512}
THRESHOLD=${THRESHOLD:-0.5}
HIGH_CONFIDENCE_THRESHOLD=${HIGH_CONFIDENCE_THRESHOLD:-0.9}
MIN_READS=${MIN_READS:-5}
MIN_MAPQ=${MIN_MAPQ:-0}
MAX_READS=${MAX_READS:-30}
MAX_IMAGES_PER_BASE=${MAX_IMAGES_PER_BASE:-5}
HALF_WINDOW=${HALF_WINDOW:-10}
SAMPLES_PER_BASE=${SAMPLES_PER_BASE:-10}
NORMALIZE=${NORMALIZE:-1}
FORCE=${FORCE:-0}

FEATURE_DIR=$OUT_DIR/features
PRED_DIR=$OUT_DIR/predictions
SUMMARY_DIR=$OUT_DIR/summary
LOG_DIR=$OUT_DIR/logs
H5=$FEATURE_DIR/$DATASET.h5
PRED=$PRED_DIR/$DATASET.deepmod_reference_predictions.tsv

choose_first_existing() {
  for path in "$@"; do
    if [[ -n "$path" && -f "$path" ]]; then
      printf '%s\n' "$path"
      return 0
    fi
  done
  return 1
}

if [[ -z "$BAM" ]]; then
  BAM=$(choose_first_existing \
    "$EVENT_DIR/reads_refined_filtered.bam" \
    "$EVENT_DIR/reads_refined.sorted.bam" \
    "$EVENT_DIR/reads_refined.bam") || {
      echo "Could not infer BAM from EVENT_DIR=$EVENT_DIR" >&2
      exit 1
    }
fi

if [[ -z "$LEVEL_TABLE" ]]; then
  LEVEL_TABLE=$(choose_first_existing \
    "$EVENT_DIR/uncalled_r1041_model_only_means.txt" \
    "$(dirname "$EVENT_DIR")/uncalled_r1041_model_only_means.txt" \
    "$WORK_ROOT/results/uncalled_r1041_model_only_means.txt") || true
fi

mkdir -p "$FEATURE_DIR" "$PRED_DIR" "$SUMMARY_DIR" "$LOG_DIR"

test -f "$MODEL"
test -e "$POD5"
test -f "$BAM"
test -f "$PEAKS"
if [[ -n "$LEVEL_TABLE" ]]; then
  test -f "$LEVEL_TABLE"
fi
if [[ -n "$REFERENCE" ]]; then
  test -f "$REFERENCE"
fi
if [[ -n "$GT_BED" ]]; then
  test -f "$GT_BED"
fi

echo "DeepMod dataset test"
echo "  dataset:     $DATASET"
echo "  event_dir:   $EVENT_DIR"
echo "  pod5:        $POD5"
echo "  bam:         $BAM"
echo "  peaks:       $PEAKS"
echo "  level_table: ${LEVEL_TABLE:-none}"
echo "  model:       $MODEL"
echo "  out_dir:     $OUT_DIR"

if [[ "$FORCE" == "1" || ! -f "$H5" ]]; then
  cmd=(
    "$PYTHON" -m deepmod.featurization
    --pod5 "$POD5"
    --bam "$BAM"
    --peaks "$PEAKS"
    --output "$H5"
    --min-reads "$MIN_READS"
    --min-mapq "$MIN_MAPQ"
    --max-reads "$MAX_READS"
    --max-images-per-base "$MAX_IMAGES_PER_BASE"
    --half-window "$HALF_WINDOW"
    --L "$SAMPLES_PER_BASE"
  )
  if [[ "$NORMALIZE" == "1" ]]; then
    cmd+=(--normalize)
  fi
  if [[ -n "$LEVEL_TABLE" ]]; then
    cmd+=(--level-table "$LEVEL_TABLE")
  fi
  if [[ -n "$GT_BED" ]]; then
    cmd+=(--gt "$GT_BED")
  fi

  echo "[$DATASET] featurizing -> $H5"
  "${cmd[@]}" > "$LOG_DIR/featurize.log" 2>&1
else
  echo "[$DATASET] using existing features: $H5"
fi

if [[ "$FORCE" == "1" || ! -f "$PRED" ]]; then
  cmd=(
    "$PYTHON" "$REPO_ROOT/scripts/evaluation/predict_deepmod_by_reference.py"
    --model "$MODEL"
    --h5 "$H5"
    --dataset "$DATASET"
    --output "$PRED"
    --batch-size "$BATCH_SIZE"
    --device "$DEVICE"
    --threshold "$THRESHOLD"
  )
  if [[ -n "$REFERENCE" ]]; then
    cmd+=(--reference "$REFERENCE")
  fi

  echo "[$DATASET] predicting -> $PRED"
  "${cmd[@]}" > "$LOG_DIR/predict.log" 2>&1
else
  echo "[$DATASET] using existing predictions: $PRED"
fi

"$PYTHON" "$REPO_ROOT/scripts/evaluation/summarize_deepmod_predictions.py" \
  --predictions "$PRED" \
  --out-dir "$SUMMARY_DIR" \
  --threshold "$THRESHOLD" \
  --high-confidence-threshold "$HIGH_CONFIDENCE_THRESHOLD" \
  > "$LOG_DIR/summarize.log" 2>&1

cat > "$OUT_DIR/README.md" <<EOF
# DeepMod Test: $DATASET

Generated by \`scripts/benchmarks/run_deepmod_dataset_test.sh\`.

## Inputs

- POD5: \`$POD5\`
- BAM: \`$BAM\`
- peaks: \`$PEAKS\`
- level table: \`${LEVEL_TABLE:-none}\`
- model: \`$MODEL\`

## Outputs

- HDF5 features: \`features/$DATASET.h5\`
- reference predictions: \`predictions/$DATASET.deepmod_reference_predictions.tsv\`
- summary metrics: \`summary/prediction_summary.tsv\`
- score histogram: \`summary/score_histogram.svg\`
- thresholded BED calls: \`summary/modified_calls_threshold_$THRESHOLD.bed\`
- logs: \`logs/\`
EOF

echo "[$DATASET] done: $OUT_DIR"
